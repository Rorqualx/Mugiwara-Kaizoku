import type { TestManga } from '../cleanup/test-parser-accuracy-corpus';

/**
 * ComicVine-specific test manga interface
 */
export interface ComicVineTestManga extends TestManga {
  /** ComicVine URL (optional - will be discovered if not provided) */
  comicvineUrl?: string;

  /** ComicVine volume ID (optional - extracted from URL if not provided) */
  comicvineVolumeId?: string;

  /** Expected language for this title (for testing language detection) */
  expectedLanguage?: 'en' | 'ja' | 'fr' | 'de' | 'es' | 'it' | 'pt' | 'ko' | 'zh';

  /** Expected publisher (for testing publisher-based language detection) */
  expectedPublisher?: string;

  /** Alternative ComicVine domains to try */
  altDomains?: string[];

  /**
   * If true, this entry is included in the `--fast-sample` run of the
   * comicvine-accuracy loop. Used to bound iteration runtime.
   * See docs/research/comicvine-accuracy/LOOP_WORKFLOW.md.
   */
  fastSample?: boolean;

  /**
   * If true, the `comicvineUrl` field has been verified against ComicVine
   * (either by hand or by `scripts/comicvine/verify-comicvine-corpus.ts`)
   * and represents the *real* main-series volume ID. Many corpus entries
   * were auto-populated with sequential placeholder IDs by an old script;
   * those have `verified: false` (or undefined) and are NOT counted toward
   * the discoveryCorrect metric until they're cleaned.
   *
   * Set to `true` only when the matcher discovered an ID with high confidence
   * (titleSimilarity >= 0.85 + language match) OR when the ID was reviewed by hand.
   */
  verified?: boolean;

  /** Free-text note about edge cases / why this entry is interesting */
  note?: string;
}

